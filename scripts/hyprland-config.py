#!/usr/bin/env python3
"""Hyprland settings backend for the iNiR Settings application.

Mirrors the CLI surface of scripts/niri-config.py for the sections that have
a verified Hyprland implementation, so the spec-driven Settings UI
(IrisNiri.qml) can route writes per compositor without format changes.

Two-tier persistence, same contract as niri-config.py:

  Runtime tier   `hyprctl eval "hl.config({ ... })"` — instant effect.
                 (`hyprctl keyword` is non-functional under the Lua config
                 provider on Hyprland >= 0.55; verified on 0.56.2.)
  Persistent tier `~/.config/hypr/custom/settings.lua` — a fully generated
                 file inside the protected custom/ directory (iNiR updates
                 never touch custom/). Hyprland watches the config tree and
                 auto-reloads it (verified: a file edit re-applies the Lua),
                 which matches niri's save-and-hot-reload semantics.

Validation before commit: `luac -p` when available, backup + restore on
failure. Reads use `hyprctl getoption <option> -j` (runtime truth).
"""

import json
import re
import subprocess
import sys
from pathlib import Path

HYPR_CONFIG_DIR = Path.home() / ".config" / "hypr"
SETTINGS_FILE = HYPR_CONFIG_DIR / "custom" / "settings.lua"

# Niri strength presets map to Hyprland blur passes (niri-config.py
# BLUR_STRENGTH light/balanced/strong = passes 2/3/4).
STRENGTH_PASSES = {"light": 2, "balanced": 3, "strong": 4}
PASSES_STRENGTH = {v: k for k, v in STRENGTH_PASSES.items()}

# Verified option names on Hyprland 0.56.2 (decoration:blur:saturation does
# not exist; vibrancy is the colour-vividness equivalent).
OPTIONS = {
    "enabled": "decoration:blur:enabled",
    "passes": "decoration:blur:passes",
    "size": "decoration:blur:size",
    "noise": "decoration:blur:noise",
    "vibrancy": "decoration:blur:vibrancy",
}


def hyprctl(args, timeout=6):
    """Run hyprctl and return stdout, or None when hyprctl is unavailable."""
    try:
        out = subprocess.run(
            ["hyprctl", *args], capture_output=True, text=True, timeout=timeout
        )
    except (FileNotFoundError, subprocess.TimeoutExpired):
        return None
    if out.returncode != 0:
        return None
    return out.stdout


def get_option(name):
    """Read one config option via hyprctl getoption -j. Returns (value, set)."""
    raw = hyprctl(["getoption", name, "-j"])
    if raw is None:
        return None, False
    try:
        data = json.loads(raw)
    except json.JSONDecodeError:
        return None, False
    for kind in ("bool", "int", "float", "str"):
        if kind in data:
            return data[kind], bool(data.get("set", False))
    return None, False


def version_string():
    raw = hyprctl(["version"])
    if not raw:
        return ""
    first = raw.strip().splitlines()[0] if raw.strip() else ""
    return first.replace("Hyprland, ", "").strip()


def read_blur_state():
    """Effective blur state in the same JSON shape as niri-config.py get-blur."""
    version = version_string()
    available = version != ""
    enabled, _ = get_option(OPTIONS["enabled"])
    passes, _ = get_option(OPTIONS["passes"])
    noise, _ = get_option(OPTIONS["noise"])
    vibrancy, _ = get_option(OPTIONS["vibrancy"])
    return {
        "available": available,
        "version": version,
        "enabled": bool(enabled) if enabled is not None else False,
        "strength": PASSES_STRENGTH.get(passes, "custom") if passes is not None else "custom",
        "noise": float(noise) if noise is not None else 0.02,
        "saturation": float(vibrancy) if vibrancy is not None else 1.5,
        "elsewhere": [],
    }


def cmd_get_blur():
    print(json.dumps(read_blur_state()))
    return 0


def eval_config(config_table):
    """Apply one hl.config({...}) table to the running compositor."""
    raw = hyprctl(["eval", f"hl.config({config_table})"])
    if raw is None:
        return False
    return "ok" in raw.lower()


def write_settings_file(blur_table):
    """(Re)generate the managed settings file with the given blur table."""
    SETTINGS_FILE.parent.mkdir(parents=True, exist_ok=True)
    backup = None
    if SETTINGS_FILE.exists():
        backup = SETTINGS_FILE.read_text()
    body = (
        "-- Generated by iNiR Settings — managed settings state.\n"
        "-- Loaded via pcall(require, \"custom.settings\") in hyprland.lua.\n"
        "-- User overrides in custom/overrides.lua load after this file and win.\n"
        f"hl.config({{\n    decoration = {{\n        blur = {blur_table},\n    }},\n}})\n"
    )
    SETTINGS_FILE.write_text(body)
    # Validate before committing: a syntax error would abort the whole config
    # (a require() of a broken module kills the invoking file chain).
    luac = _luac_check(SETTINGS_FILE)
    if luac is False:
        if backup is not None:
            SETTINGS_FILE.write_text(backup)
        else:
            SETTINGS_FILE.unlink()
        return False
    return True


def _luac_check(path):
    try:
        out = subprocess.run(["luac", "-p", str(path)], capture_output=True, timeout=10)
    except FileNotFoundError:
        return None  # validator unavailable — accept (generated content)
    except subprocess.TimeoutExpired:
        return False
    return out.returncode == 0


def blur_table_from_state(state):
    """Render the Lua blur table from a state dict (same key names as niri)."""
    entries = [
        f"enabled = {'true' if state.get('enabled') else 'false'}",
        f"size = {int(state.get('size', 8))}",
        f"passes = {int(state.get('passes', 3))}",
        f"noise = {float(state.get('noise', 0.02)):.4f}",
        f"vibrancy = {float(state.get('saturation', 1.5)):.4f}",
    ]
    return "{ " + ", ".join(entries) + " }"


def current_state_for_write():
    """Effective values (getoption) rendered in the niri state key names."""
    enabled, _ = get_option(OPTIONS["enabled"])
    passes, _ = get_option(OPTIONS["passes"])
    size, _ = get_option(OPTIONS["size"])
    noise, _ = get_option(OPTIONS["noise"])
    vibrancy, _ = get_option(OPTIONS["vibrancy"])
    return {
        "enabled": bool(enabled) if enabled is not None else False,
        "passes": int(passes) if passes is not None else 3,
        "size": int(size) if size is not None else 8,
        "noise": float(noise) if noise is not None else 0.02,
        "saturation": float(vibrancy) if vibrancy is not None else 1.5,
    }


def cmd_set_blur(key, value):
    state = current_state_for_write()
    if key == "enabled":
        normalized = str(value).strip().lower()
        if normalized in ("on", "true", "1"):
            state["enabled"] = True
        elif normalized in ("off", "false", "0"):
            state["enabled"] = False
        else:
            print(json.dumps({"error": f"invalid blur enabled value: {value}"}))
            return 1
    elif key == "strength":
        if str(value).strip().lower() not in STRENGTH_PASSES:
            print(json.dumps({"error": f"invalid blur strength: {value}"}))
            return 1
        state["passes"] = STRENGTH_PASSES[str(value).strip().lower()]
    elif key == "noise":
        try:
            state["noise"] = max(0.0, min(1.0, float(value)))
        except ValueError:
            print(json.dumps({"error": f"invalid blur noise value: {value}"}))
            return 1
    elif key == "saturation":
        try:
            state["saturation"] = max(0.0, min(4.0, float(value)))
        except ValueError:
            print(json.dumps({"error": f"invalid blur saturation value: {value}"}))
            return 1
    else:
        print(json.dumps({"error": f"unsupported blur key: {key}"}))
        return 1

    table = blur_table_from_state(state)
    if not write_settings_file(table):
        print(json.dumps({"error": "settings file validation failed; change reverted"}))
        return 1
    # Instant effect; the generated file also auto-reloads (verified), which
    # re-applies identical values — idempotent.
    eval_config(f"{{ decoration = {{ blur = {table} }} }}")
    print(json.dumps({"ok": True, "key": key, "value": value, "state": state}))
    return 0


# ── Keybinds ────────────────────────────────────────────────────────────────
# The cheatsheet/display model is built from the ACTIVE config sources
# (~/.config/hypr/inir/binds.lua + custom/overrides.lua), validated against
# `hyprctl -j binds` so parsed-but-inactive entries never display.

MOD_BITS = {"SHIFT": 1, "CAPSLOCK": 2, "CTRL": 4, "CONTROL": 4, "ALT": 8,
            "MOD2": 16, "MOD3": 32, "SUPER": 64, "WIN": 64, "LOGO": 64}

CATEGORY_RULES = [
    ("System", ("exit", "quit", "session", "power", "lock", "logout", "shutdown")),
    ("iNiR Shell", ("inir", "settings", "overview", "clipboard", "cheatsheet", "panelfamily")),
    ("Screenshots", ("region", "screenshot", "capture", "grim", "record")),
    ("Applications", ("exec_cmd", "terminal", "browser", "files", "launcher")),
    ("Workspaces", ("workspace",)),
    ("Window Management", ("window.", "close", "float", "fullscreen", "pseudo", "pin")),
    ("Focus", ("focus",)),
    ("Move Windows", ("window.move", "movewindow", "swap", "drag")),
    ("Media", ("vol", "audio", "media", "player", "mute")),
    ("Brightness", ("brightness", "dpms", "backlight")),
]


def hypr_binds():
    raw = hyprctl(["-j", "binds"])
    if raw is None:
        return []
    try:
        data = json.loads(raw)
    except json.JSONDecodeError:
        return []
    return data if isinstance(data, list) else []


def active_key_set(binds):
    """Set of (modmask_without_super_variants, key.upper()) from hyprctl binds."""
    keys = set()
    for b in binds:
        key = str(b.get("key", "")).upper()
        keys.add((int(b.get("modmask", 0)), key))
    return keys


def parse_lua_mods(keys_expr, local_mods):
    """'M .. \" + SHIFT + E\"' -> (modmask, 'E'). Resolves simple locals."""
    text = keys_expr.strip()
    for name, value in local_mods.items():
        text = re.sub(rf"\b{name}\b", value, text)
    mask = 0
    key = ""
    for part in re.split(r"\.\.|\+", text):
        token = part.strip().strip("'\"")
        if not token:
            continue
        upper = token.upper()
        if upper in MOD_BITS:
            mask |= MOD_BITS[upper]
        else:
            key = token.upper()
    return mask, key


def describe_dispatcher(dispatcher):
    """Human comment for a hl.dsp.* expression or function body."""
    d = dispatcher.strip()
    m = re.search(r'exec_cmd\(\s*"([^"]+)"', d)
    if m:
        return m.group(1)
    m = re.search(r"hl\.dsp\.(?:window\.)?(\w+)\s*\(([^)]*)\)", d)
    if m:
        action, args = m.group(1), m.group(2).strip()
        pretty = action.replace("_", " ")
        return f"{pretty}: {args}" if args and args not in ("{ workspace = %s }",) else pretty
    if d.startswith("function"):
        inner = re.search(r"hl\.dsp\.[\w.]+\(([^)]*)\)", d)
        if inner:
            name = re.search(r"hl\.dsp\.([\w.]+)\(", d)
            arg = inner.group(1).strip().strip('"')
            return f"{name.group(1)}: {arg}" if arg else name.group(1)
        return "custom action"
    return d[:60] or "custom action"


def categorize(comment):
    lowered = comment.lower()
    for category, needles in CATEGORY_RULES:
        if any(n in lowered for n in needles):
            return category
    return "Other"


def lua_bind_sources():
    """Yield (path, text) for the active config's bind sources."""
    sources = [HYPR_CONFIG_DIR / "inir" / "binds.lua",
               HYPR_CONFIG_DIR / "custom" / "overrides.lua"]
    for path in sources:
        if path.exists():
            yield path, path.read_text(errors="replace")


def parse_lua_binds():
    """Parse hl.bind(...) entries from the active config sources.

    Multi-line binds (function dispatchers) are accumulated until the
    parentheses balance so no active bind is silently missed.
    """
    binds = []
    for path, text in lua_bind_sources():
        local_mods = {}
        for m in re.finditer(r"^\s*local\s+(\w+)\s*=\s*[\"']([A-Za-z0-9 +]+)[\"']", text, re.M):
            local_mods[m.group(1)] = m.group(2)
        lines = text.splitlines()
        i = 0
        while i < len(lines):
            stripped = lines[i].strip()
            i += 1
            if not stripped.startswith("hl.bind("):
                continue
            # Accumulate until the statement's parentheses balance. The delta
            # is computed per line (comments stripped for counting) — never
            # over the whole statement, which would double-count.
            def _delta(line):
                return (re.sub(r"--.*$", "", line).count("(")
                        - re.sub(r"--.*$", "", line).count(")"))

            stmt, depth = stripped, _delta(stripped)
            while depth > 0 and i < len(lines):
                line = lines[i].strip()
                i += 1
                stmt += " " + line
                depth += _delta(line)
            trailing = ""
            tm = re.search(r"\)\s*--\s*(.*)$", stmt)
            if tm:
                trailing = tm.group(1).strip()
                stmt = stmt[: tm.start()] + ")"
            m = re.match(r"hl\.bind\((.*)\)$", stmt)
            if not m:
                continue
            args_text, opts = m.group(1), ""
            om = re.search(r",\s*\{\s*description\s*=\s*[\"']([^\"']+)[\"'].*\}\s*$", args_text)
            if om:
                opts = om.group(1)
                args_text = args_text[: om.start()]
            parts = _split_bind_args(args_text)
            if len(parts) < 2:
                continue
            mask, key = parse_lua_mods(parts[0], local_mods)
            if not key:
                continue
            description = opts or trailing or describe_dispatcher(parts[1])
            binds.append({
                "modmask": mask,
                "key": key,
                "action_raw": parts[1].strip(),
                "comment": description,
                "category": categorize(description),
                "source": str(path),
                "line": i,
            })
    return binds


def _split_bind_args(args_text):
    """Split top-level comma-separated Lua args, honoring quotes/braces/funcs."""
    parts, depth, quote, current = [], 0, "", []
    for ch in args_text:
        if quote:
            current.append(ch)
            if ch == quote:
                quote = ""
            continue
        if ch in "\"'":
            quote = ch
            current.append(ch)
            continue
        if ch in "({[":
            depth += 1
        elif ch in ")}]":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append("".join(current).strip())
            current = []
            continue
        current.append(ch)
    tail = "".join(current).strip()
    if tail:
        parts.append(tail)
    return parts


def cmd_get_binds():
    """Cheatsheet model: active, source-validated binds grouped by category."""
    binds = hypr_binds()
    if not binds:
        print(json.dumps({"error": "hyprctl binds unavailable", "children": []}))
        return 1
    active = active_key_set(binds)
    parsed = [b for b in parse_lua_binds() if (b["modmask"], b["key"]) in active]
    by_category = {}
    for b in parsed:
        by_category.setdefault(b["category"], []).append(
            {"mods": _mod_names(b["modmask"]), "key": b["key"], "comment": b["comment"]}
        )
    order = ["System", "iNiR Shell", "Window Switcher", "Screenshots", "Applications",
             "Window Management", "Layout", "Resize", "Focus", "Move Windows",
             "Monitors", "Workspaces", "Media", "Brightness", "Other"]
    children = []
    for cat in order:
        if by_category.get(cat):
            children.append({"name": cat, "children": [{"keybinds": by_category[cat]}]})
    for cat, entries in sorted(by_category.items()):
        if cat not in order and entries:
            children.append({"name": cat, "children": [{"keybinds": entries}]})
    print(json.dumps({"children": children, "configPath": str(HYPR_CONFIG_DIR / "inir" / "binds.lua"),
                      "activeBinds": len(binds), "matchedBinds": len(parsed)}))
    return 0


def _mod_names(mask):
    names = []
    for bit, name in ((1, "Shift"), (4, "Ctrl"), (8, "Alt"), (64, "Super")):
        if mask & bit:
            names.append(name)
    return names


def main():
    args = sys.argv[1:]
    if not args:
        print(json.dumps({"error": "usage: hyprland-config.py <get-blur|set blur <key> <value>|get-binds>"}))
        return 1
    if args[0] == "get-blur":
        return cmd_get_blur()
    if args[0] == "get-binds":
        return cmd_get_binds()
    if args[0] == "set" and len(args) >= 4 and args[1] == "blur":
        return cmd_set_blur(args[2], args[3])
    print(json.dumps({"error": f"unknown command: {' '.join(args)}"}))
    return 1


if __name__ == "__main__":
    sys.exit(main())
